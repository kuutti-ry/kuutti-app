import { describe, expect, it } from "vitest";
import { compile } from "./compile.ts";
import type { Messages } from "./schema.ts";

// What `pnpm i18n:build` writes (#13, #46): one catalogue per locale, the
// pseudo-locale, the typed keys, the consent versions of legal.* text, and
// the strings the phone's own system shows for the app (#418).

const base: Messages = {
  "demo.hello": { en: "Hello {name}", description: "d", fi: "Hei {name}", machine: { fi: true } },
  "demo.count": {
    en: "{n, plural, one {# day} other {# days}}",
    description: "d",
    sv: "{n, plural, one {# dag} other {# dagar}}",
    machine: { sv: true },
  },
  "demo.when": { en: "On {at, date, short}", description: "d" },
  "admin.title": { en: "Kuutti admin", description: "English only." },
};

describe("the catalogues", () => {
  const out = compile(base);

  it("are six modules and the native strings' JSON", () => {
    expect(Object.keys(out).sort()).toEqual(
      ["consent.ts", "en-XA.ts", "en.ts", "fi.ts", "keys.ts", "native.json", "sv.ts"].sort(),
    );
    for (const [name, module] of Object.entries(out)) {
      if (!name.endsWith(".ts")) continue;
      expect([name, module.startsWith("// Generated by `pnpm i18n:build`")]).toEqual([name, true]);
    }
  });

  it("hold a locale's own texts only, sorted by key, so a missing one falls back at run time", () => {
    expect(out["fi.ts"]).toContain('"demo.hello": "Hei {name}",');
    expect(out["fi.ts"]).not.toContain("demo.count");
    expect(out["sv.ts"]).toContain('"demo.count"');
    expect(out["sv.ts"]).not.toContain("demo.hello");
    const en = out["en.ts"] ?? "";
    expect(en.indexOf('"admin.title"')).toBeLessThan(en.indexOf('"demo.count"'));
    expect(en.indexOf('"demo.count"')).toBeLessThan(en.indexOf('"demo.hello"'));
  });

  it("pseudo-localise the English but leave the English-only admin panel alone", () => {
    expect(out["en-XA.ts"]).toContain('"admin.title": "Kuutti admin"');
    expect(out["en-XA.ts"]).toContain('"demo.hello": "［Hééllóó {name}］"');
  });
});

describe("the key types", () => {
  it("demand each argument with the type its format needs, and nothing for a plain key", () => {
    const keys = compile(base)["keys.ts"] ?? "";
    expect(keys).toContain('"demo.hello": { "name": string };');
    expect(keys).toContain('"demo.count": { "n": number };');
    expect(keys).toContain('"demo.when": { "at": Date | number };');
    expect(keys).toContain('"admin.title": Record<never, never>;');
    expect(keys).toContain("export type MessageKey = keyof MessageParams;");
  });
});

describe("the consent versions", () => {
  const legal = (fields: Partial<Messages[string]>): Messages[string] => ({
    en: "Text",
    description: "d",
    consent_version: "2026-09-01",
    ...fields,
  });

  it("name one version per kind, the languages each wording exists in, and a hash of its Finnish", () => {
    const out = compile({
      ...base,
      "legal.terms.title": legal({ fi: "Käyttöehdot", sv: "Villkor" }),
      "legal.terms.body": legal({ fi: "Ehdot" }),
      "legal.privacy.title": legal({ consent_version: "3", fi: "Tietosuoja" }),
    })["consent.ts"];
    expect(out).toContain('"privacy": "3",');
    expect(out).toContain('"terms": "2026-09-01",');
    expect(out).toContain('"terms": ["en","fi","sv"],');
    expect(out).toContain('"privacy": ["en","fi"],');
    // Sorted by kind.
    expect(out?.indexOf('"privacy"')).toBeLessThan(out?.indexOf('"terms"') ?? 0);
    expect(out).toMatch(/"terms": "[0-9a-f]{16}",/);
  });

  it("hash the Finnish wording, so the hash moves when the Finnish does and not when the order does", () => {
    const hashOf = (messages: Messages) =>
      /CONSENT_TEXT_HASHES[^{]*\{\n {2}"terms": "([0-9a-f]{16})"/.exec(
        compile(messages)["consent.ts"] ?? "",
      )?.[1];
    const a = { "legal.terms.a": legal({ fi: "Yksi" }), "legal.terms.b": legal({ fi: "Kaksi" }) };
    const swapped = { "legal.terms.b": a["legal.terms.b"], "legal.terms.a": a["legal.terms.a"] };
    const edited = { ...a, "legal.terms.b": legal({ fi: "Kolme" }) };
    expect(hashOf(a)).toBe(hashOf(swapped));
    expect(hashOf(a)).not.toBe(hashOf(edited));
  });

  it("count a wording without its Finnish yet, as an empty Finnish text", () => {
    const out = compile({ "legal.research.title": legal({}) })["consent.ts"];
    expect(out).toContain('"research": "2026-09-01",');
    expect(out).toContain('"research": ["en"],');
  });

  it("ignore keys outside legal.* and legal keys without a version", () => {
    const unversioned = { "legal.terms.title": { en: "Terms", description: "d", fi: "Ehdot" } };
    const out = compile({ ...base, ...unversioned })["consent.ts"];
    expect(out).toContain("CONSENT_VERSIONS: Readonly<Record<string, string>> = {\n\n};");
  });

  it("refuse two versions under one kind: one wording, one version", () => {
    expect(() =>
      compile({
        "legal.terms.title": legal({ fi: "Ehdot" }),
        "legal.terms.body": legal({ fi: "Ehdot", consent_version: "2026-10-01" }),
      }),
    ).toThrow(
      "legal.terms.* carries 2 consent versions (2026-09-01, 2026-10-01): one wording, one version",
    );
  });
});

describe("the native strings", () => {
  const native = (fields: Partial<Messages[string]>): Messages[string] => ({
    en: "Text",
    description: "d",
    ...fields,
  });
  const nativeOf = (messages: Messages) => JSON.parse(compile(messages)["native.json"] ?? "");

  it("are an empty object when no key is native, as JSON alone with no header", () => {
    expect(compile(base)["native.json"]).toBe("{}\n");
  });

  it("nest each text under its locale, its platform and its key, a locale only where the text exists", () => {
    const out = nativeOf({
      ...base,
      "native.ios.NSFaceIDUsageDescription": native({
        en: "Face ID opens Kuutti.",
        fi: "Face ID avaa Kuutin.",
        sv: "Face ID öppnar Kuutti.",
      }),
      "native.ios.NSCameraUsageDescription": native({ en: "The camera takes a photo." }),
      "native.android.app_name": native({ en: "Kuutti", fi: "Kuutti" }),
    });
    expect(out).toEqual({
      en: {
        android: { app_name: "Kuutti" },
        ios: {
          NSCameraUsageDescription: "The camera takes a photo.",
          NSFaceIDUsageDescription: "Face ID opens Kuutti.",
        },
      },
      fi: {
        android: { app_name: "Kuutti" },
        ios: { NSFaceIDUsageDescription: "Face ID avaa Kuutin." },
      },
      sv: { ios: { NSFaceIDUsageDescription: "Face ID öppnar Kuutti." } },
    });
    // Nothing of a key outside native.*, and nothing of the pseudo-locale.
    expect(JSON.stringify(out)).not.toContain("demo.");
    expect(Object.keys(out)).toEqual(["en", "fi", "sv"]);
  });

  it("are sorted by key whatever the order of messages.yaml, so the file moves only when a text does", () => {
    const b = native({ en: "B" });
    const a = native({ en: "A" });
    const one = compile({ "native.ios.B": b, "native.ios.A": a })["native.json"];
    const other = compile({ "native.ios.A": a, "native.ios.B": b })["native.json"];
    expect(one).toBe(other);
    expect(Object.keys(JSON.parse(one ?? "").en.ios)).toEqual(["A", "B"]);
    expect(one).toBe(`${JSON.stringify({ en: { ios: { A: "A", B: "B" } } }, null, 2)}\n`);
  });

  it("leave out keys that only begin or contain the word native", () => {
    const out = compile({
      "nativeish.ios.Key": native({}),
      "settings.native.ios": native({}),
    })["native.json"];
    expect(out).toBe("{}\n");
  });

  it.each([
    ["native"],
    ["native.ios"],
    ["native.x"],
    ["native..Key"],
    ["native.ios."],
    ["native.a.b.c"],
    ["native.ios.Key.extra"],
  ])("refuse %s, which is not native.<platform>.<key>", (key) => {
    expect(() => compile({ ...base, [key]: native({}) })).toThrow(
      `${key}: a native string is native.<platform>.<key>`,
    );
  });

  it.each([
    ["en", "a double quote", { en: 'Kuutti uses "Face ID".' }],
    ["fi", "a backslash", { fi: "Kuutti\\n käyttää Face ID:tä." }],
    ["sv", "a double quote", { sv: 'Kuutti använder "Face ID".' }],
    ["en", "a backslash alone", { en: "\\" }],
  ] as const)(
    "refuse %s text with %s, which a native strings file cannot carry",
    (locale, _what, texts) => {
      expect(() => compile({ "native.ios.NSFaceIDUsageDescription": native(texts) })).toThrow(
        `native.ios.NSFaceIDUsageDescription: ${locale} carries a double quote or a backslash, which a native strings file cannot`,
      );
    },
  );

  it("take a single quote, an apostrophe and letters beyond ASCII as they are", () => {
    const text = "Kuutti's lock — Face ID:tä, låset ’ok’.";
    expect(nativeOf({ "native.ios.K": native({ en: text, sv: text }) })).toEqual({
      en: { ios: { K: text } },
      sv: { ios: { K: text } },
    });
  });
});
